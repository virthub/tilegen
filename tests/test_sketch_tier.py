# tests/test_sketch_tier.py
#
# Tests for the sketch-tier guardrails: unmatched VTM patterns (including
# ring_step) emit a loud NOT-RUNNABLE banner, strict mode raises, and the
# four runnable patterns are never flagged.

import pytest

from tilegen.backend import ensure_backends_registered, get_backend
from tilegen.ir.builder import VTMBuilder
from tilegen.layout.quant import QuantSpec
from tilegen.ops.attention import AttentionSpec, build_attention_vtm
from tilegen.target.spec import get_target


def _ring_kernel():
    """A minimal ring-attention VTM: matmul + ring_step, no gathered pages."""
    builder = VTMBuilder(name="ring_attn")
    builder.input("Q", ("B", "H", "N", "D"))
    builder.input("K", ("B", "H", "N", "D"))
    builder.input("V", ("B", "H", "N", "D"))
    builder.alloc("A", ("B", "H", "N", "N"))
    builder.output("O", ("B", "H", "N", "D"))
    builder.matmul("Q", "K", "A")
    builder.ring_step(send="K", recv="K")
    builder.matmul("A", "V", "O")
    return builder.build()


def _lower_triton(kernel):
    ensure_backends_registered()
    return get_backend("triton").lower(kernel, get_target("sm_90a"))


class TestSketchTier:
    def test_ring_kernel_emits_banner(self):
        src = _lower_triton(_ring_kernel())
        assert src.startswith("# Auto-generated by TileGen")
        assert "# SKETCH TIER - NOT RUNNABLE - ring_step has no lowering" in src

    def test_strict_mode_raises(self, monkeypatch):
        monkeypatch.setenv("TILEGEN_STRICT_CODEGEN", "1")
        with pytest.raises(RuntimeError, match="SKETCH TIER"):
            _lower_triton(_ring_kernel())

    def test_runnable_patterns_are_not_flagged(self):
# The dense FA2 pattern (pipeline loop + matmul, K/V inputs) is
        # dispatch-matched to runnable codegen and must never be flagged.
        from tilegen.ops.attention import build_dense_attention_vtm

        spec = AttentionSpec(batch=1, num_heads=8, head_dim=64,
                             seq_len=512, causal=True)
        kernel = build_dense_attention_vtm(spec, get_target("sm_90a"),
                                           variant="fa2_prefill")
        src = _lower_triton(kernel)
        assert "# SKETCH TIER" not in src
