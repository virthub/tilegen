# TileLang lowering backend

from __future__ import annotations

from tilegen.backend._common import (
    SKETCH_BANNER,
    TILELANG_DTYPE,
    guard_sketch,
    header,
    shape_str,
    sketch_reason,
    var,
)
from tilegen.backend.base import Backend, register_backend
from tilegen.ir.ops import (
    DequantOp,
    LoadOp,
    MaskOp,
    MatmulOp,
    OnlineSoftmaxOp,
    PipelineForOp,
    StoreOp,
    VTMKernel,
    VTMOp,
)
from tilegen.ir.topology import GridMode
from tilegen.ir.types import MemoryTier, VTMBuffer
from tilegen.target.spec import TargetSpec

INDENT = "        "


def _dtype(dt: str) -> str:
    return TILELANG_DTYPE.get(dt, dt)


def _walk(ops):
    for op in ops:
        yield op
        if isinstance(op, PipelineForOp):
            yield from _walk(op.body)


def _dim(d) -> int:
    return d.value if hasattr(d, "value") else int(d)


def _is_dense_attention(kernel: VTMKernel) -> bool:
    names = {b.name for b in kernel.inputs}
    if "K" not in names or "V" not in names:
        return False
    ops = list(_walk(kernel.body))
    return any(isinstance(o, PipelineForOp) for o in ops) and any(
        isinstance(o, MatmulOp) for o in ops
    )


def _variant_of(kernel: VTMKernel) -> str:
    """Infer the FA variant (fa1/fa2/fa3/fa4) from the $M_0$ structural levers."""
    g = kernel.topology.grid
    k = kernel.topology.knobs
    if g.cta_group == 2 or k.exp_emulation_ratio > 0.0:
        return "fa4"
    if g.mode == GridMode.PERSISTENT_SM:
        return "fa3"
    if k.tile_m == 64:
        return "fa1"
    return "fa2"


_TILELANG_TARGET = {"cuda": "cuda", "rocm": "hip", "ascend": "ascend"}


class TileLangBackend(Backend):
    name = "tilelang"

    def lower(self, kernel: VTMKernel, target: TargetSpec) -> str:
        if _is_dense_attention(kernel):
            return self._lower_dense_attention(kernel, target)
        self._use_tmem = target.supports("tensor_memory")
        guard_sketch(kernel)
        lines: list[str] = [header(kernel, target, "tilelang"),
                            f"{SKETCH_BANNER} - {sketch_reason(kernel)}"]
        lines += [
            "import tilelang",
            "import tilelang.language as T",
            "",
            "",
            "@tilelang.jit(out_idx=[], target='cuda')",
            f"def {kernel.name}({self._signature(kernel)}):",
        ]
        knobs = kernel.topology.knobs
        lines.append(f"    with T.Kernel({self._grid(kernel)}, threads={self._threads(knobs)}) as bx:")
        lines.append(
            f"{INDENT}# $M_0: grid={kernel.topology.grid.mode.value}, "
            f"roles={kernel.topology.roles.phase_mode.value}, "
            f"swizzle={knobs.swizzle_mode}"
        )
        for b in kernel.buffers:
            lines.append(self._alloc(b))
        lines.append("")
        for op in kernel.body:
            lines.extend(self._emit(op, depth=1))
        lines.append(f"{INDENT}return {', '.join(b.name for b in kernel.outputs)}")
        return "\n".join(lines) + "\n"

    def _lower_dense_attention(self, kernel: VTMKernel, target: TargetSpec) -> str:
        """Emit a *runnable* TileLang dense flash attention (FA1-FA4).

        ``T.gemm`` abstracts the MMA instruction per toolchain (tcgen05 on
        Blackwell = FA4, wgmma on Hopper = FA3, mfma on CDNA3), and
        ``T.Pipelined(num_stages=...)`` lowers to producer/consumer warp
        specialization on Hopper/Blackwell.  The single body is therefore
        FA1-FA4-generic: the variant is selected by the topology's tile/stages
        knobs and structural levers, and only the ``target=`` flag + label change.
        """
        q = next(b for b in kernel.inputs if b.name == "Q")
        batch = _dim(q.shape[0])
        heads = _dim(q.shape[1])
        seq = _dim(q.shape[2])
        dim = _dim(q.shape[3])
        tl_dtype = "T.bfloat16" if q.dtype == "bf16" else "T.float16"
        causal = any(
            isinstance(op, MaskOp) and op.type == "CAUSAL"
            for op in _walk(kernel.body)
        )
        target_flag = _TILELANG_TARGET.get(target.device, "cuda")
        variant = _variant_of(kernel)
        knobs = kernel.topology.knobs
        block_m = knobs.tile_m or 128
        block_n = knobs.tile_n or 128
        stages = knobs.pipeline_stages or 2

        L = [
            f"# Generated by TileGen TileLang backend (runnable {variant.upper()}, target={target_flag}).",
            "import os",
            "# TileLang 0.1.12 cutlass is incompatible with CUDA 13.x; use system CUDA 12.8.",
            "if 'CUDA_HOME' not in os.environ and os.path.isdir('/usr/local/cuda-12.8'):",
            "    os.environ['CUDA_HOME'] = '/usr/local/cuda-12.8'",
            "import tilelang",
            "import tilelang.language as T",
            "",
            "",
            "@tilelang.jit(out_idx=[3], target='" + target_flag + "',",
            "                pass_configs={tilelang.PassConfigKey.TL_ENABLE_FAST_MATH: True})",
            f"def {kernel.name}(batch, heads, seq_q, seq_kv, dim, is_causal,",
            f"                 block_M={block_m}, block_N={block_n}, num_stages={stages}, threads=256):",
            "    scale = (1.0 / dim) ** 0.5 * 1.44269504",
            f"    dtype = {tl_dtype}",
            "    accum_dtype = T.float32",
            "    past_len = seq_kv - seq_q",
            "",
            "    @T.prim_func",
            "    def main(",
            "        Q: T.Tensor((batch, heads, seq_q, dim), dtype),",
            "        K: T.Tensor((batch, heads, seq_kv, dim), dtype),",
            "        V: T.Tensor((batch, heads, seq_kv, dim), dtype),",
            "        Output: T.Tensor((batch, heads, seq_q, dim), dtype),",
            "    ):",
            "        with T.Kernel(T.ceildiv(seq_q, block_M), heads, batch, threads=threads) as (bx, by, bz):",
            "            Q_shared = T.alloc_shared([block_M, dim], dtype)",
            "            K_shared = T.alloc_shared([block_N, dim], dtype)",
            "            V_shared = T.alloc_shared([block_N, dim], dtype)",
            "            O_shared = T.alloc_shared([block_M, dim], dtype)",
            "            acc_s = T.alloc_fragment([block_M, block_N], accum_dtype)",
            "            acc_s_cast = T.alloc_fragment([block_M, block_N], dtype)",
            "            acc_o = T.alloc_fragment([block_M, dim], accum_dtype)",
            "            scores_max = T.alloc_fragment([block_M], accum_dtype)",
            "            scores_max_prev = T.alloc_fragment([block_M], accum_dtype)",
            "            scores_scale = T.alloc_fragment([block_M], accum_dtype)",
            "            scores_sum = T.alloc_fragment([block_M], accum_dtype)",
            "            logsum = T.alloc_fragment([block_M], accum_dtype)",
            "",
            "            T.copy(Q[bz, by, bx * block_M:(bx + 1) * block_M, :], Q_shared)",
            "            T.fill(acc_o, 0)",
            "            T.fill(logsum, 0)",
            "            T.fill(scores_max, -T.infinity(accum_dtype))",
            "",
            "            loop_range = (",
            "                T.min(T.ceildiv(seq_kv, block_N),",
            "                      T.ceildiv((bx + 1) * block_M + past_len, block_N))",
            "                if is_causal else T.ceildiv(seq_kv, block_N)",
            "            )",
            "",
            "            for k in T.Pipelined(loop_range, num_stages=num_stages):",
            "                T.copy(K[bz, by, k * block_N:(k + 1) * block_N, :], K_shared)",
            "                if is_causal:",
            "                    for i, j in T.Parallel(block_M, block_N):",
            "                        q_idx = bx * block_M + i + past_len",
            "                        k_idx = k * block_N + j",
            "                        acc_s[i, j] = T.if_then_else(q_idx >= k_idx, 0, -T.infinity(accum_dtype))",
            "                else:",
            "                    for i, j in T.Parallel(block_M, block_N):",
            "                        acc_s[i, j] = T.if_then_else(k * block_N + j >= seq_kv, -T.infinity(accum_dtype), 0)",
            "                T.gemm(Q_shared, K_shared, acc_s, transpose_B=True, policy=T.GemmWarpPolicy.FullRow)",
            "",
            "                T.copy(scores_max, scores_max_prev)",
            "                T.fill(scores_max, -T.infinity(accum_dtype))",
            "                T.reduce_max(acc_s, scores_max, dim=1, clear=False)",
            "                for i in T.Parallel(block_M):",
            "                    scores_max[i] = T.max(scores_max[i], scores_max_prev[i])",
            "                for i in T.Parallel(block_M):",
            "                    scores_scale[i] = T.exp2(scores_max_prev[i] * scale - scores_max[i] * scale)",
            "                for i, j in T.Parallel(block_M, block_N):",
            "                    acc_s[i, j] = T.exp2(acc_s[i, j] * scale - scores_max[i] * scale)",
            "                T.reduce_sum(acc_s, scores_sum, dim=1)",
            "                for i in T.Parallel(block_M):",
            "                    logsum[i] = logsum[i] * scores_scale[i] + scores_sum[i]",
            "                T.copy(acc_s, acc_s_cast)",
            "",
            "                for i, j in T.Parallel(block_M, dim):",
            "                    acc_o[i, j] *= scores_scale[i]",
            "                T.copy(V[bz, by, k * block_N:(k + 1) * block_N, :], V_shared)",
            "                T.gemm(acc_s_cast, V_shared, acc_o, policy=T.GemmWarpPolicy.FullRow)",
            "",
            "            for i, j in T.Parallel(block_M, dim):",
            "                acc_o[i, j] /= logsum[i]",
            "            T.copy(acc_o, O_shared)",
            "            T.copy(O_shared, Output[bz, by, bx * block_M:(bx + 1) * block_M, :])",
            "",
            "    return main",
            "",
            "",
            f"def {kernel.name}_forward(q, k, v, is_causal, block_m={block_m}, block_n={block_n}, num_stages=None):",
            "    B, H, N, D = q.shape",
            "    if num_stages is None:",
            "        num_stages = 1 if D >= 128 else 2",
            f"    kernel = {kernel.name}(B, H, N, N, D, is_causal, block_m, block_n, num_stages, 256)",
            "    return kernel(q, k, v)",
        ]
        return "\n".join(L) + "\n"

    def _signature(self, kernel: VTMKernel) -> str:
        args = []
        for b in kernel.inputs:
            args.append(f"{b.name}: T.Tensor({shape_str(b.shape)}, {_dtype(b.dtype)})")
        return ", ".join(args)

    def _grid(self, kernel: VTMKernel) -> str:
        if kernel.topology.grid.mode.value == "persistent_sm":
            return "T.ceildiv(batch * num_heads, num_sms)"
        return "1"

    def _threads(self, knobs) -> int:
        return 128 if knobs.tile_m == 128 else 256

    def _alloc(self, buf: VTMBuffer) -> str:
        if buf.tier == MemoryTier.ACCUMULATOR:
            kind = "T.alloc_tmem" if self._use_tmem else "T.alloc_fragment"
        elif buf.tier == MemoryTier.SCRATCHPAD:
            kind = "T.alloc_shared"
        else:
            kind = "T.alloc_fragment"
        swizzle = ""
        if buf.tier == MemoryTier.SCRATCHPAD and buf.swizzle and buf.swizzle != "NONE":
            swizzle = f"  # swizzle {buf.swizzle}"
        return f"{INDENT}{buf.name} = {kind}({shape_str(buf.shape)}, {_dtype(buf.dtype)}){swizzle}"

    def _emit(self, op: VTMOp, depth: int) -> list[str]:
        ind = INDENT * depth
        if isinstance(op, LoadOp):
            return [f"{ind}T.copy({op.source}, {op.dest})"]
        if isinstance(op, DequantOp):
            return [
                f"{ind}# dequant @{op.quant} -> {op.dest} "
                f"({op.materialize.value.upper()} bit-unpack)",
                f"{ind}T.copy({op.source}, {op.dest})",
            ]
        if isinstance(op, MatmulOp):
            return [
                f"{ind}T.gemm({op.a}, {op.b}, {op.acc}, "
                f"transpose_B={str(op.transpose_b)}, clear_accum={str(op.clear)})"
            ]
        if isinstance(op, MaskOp):
            return [f"{ind}# mask({op.type}) on {op.acc}"]
        if isinstance(op, OnlineSoftmaxOp):
            tag = "final" if op.is_final else "online"
            return [
                f"{ind}T.copy({op.acc}, {op.out})  # {tag} softmax "
                f"scale={op.scale}, emu_ratio={op.exp_emulation_ratio}"
            ]
        if isinstance(op, StoreOp):
            return [f"{ind}T.copy({op.source}, {op.dest})"]
        if isinstance(op, PipelineForOp):
            head = f"{ind}for {var(op.induction)} in T.Pipelined({var(op.end)}, num_stages={op.stages}):"
            body: list[str] = [head]
            for inner in op.body:
                body.extend(self._emit(inner, depth + 1))
            return body
        return [f"{ind}# unknown op {op.op}"]


register_backend(TileLangBackend())

__all__ = ["TileLangBackend"]
