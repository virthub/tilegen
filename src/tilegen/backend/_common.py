def header(kernel: VTMKernel, target, backend: str) -> str:
    return (
        f"# Auto-generated by TileGen v0.1.0\n"
        f"#   kernel      : {kernel.name}\n"
        f"#   backend     : {backend}\n"
        f"#   target      : {target.name} ({target.arch})\n"
        f"#   semantic_id : {semantic_hash({'kernel': kernel.to_dict(), 'target': target.to_dict(), 'backend': backend})}\n"
    )


