from __future__ import annotations

from tilegen.ir.ops import VTMKernel
from tilegen.ir.types import SymbolicDim, VTMBuffer
from tilegen.runtime.hash import semantic_hash


def shape_str(shape: tuple) -> str:
    """Format a VTM shape as a backend dimension tuple."""
    return "(" + ", ".join(_dim_str(d) for d in shape) + ")"


def var(name: str) -> str:
    """Strip the VTM-text ``%`` prefix from an identifier for host codegen."""
    return name.lstrip("%")


def _dim_str(dim) -> str:
    if isinstance(dim, SymbolicDim):
        return str(dim.value) if dim.value is not None else dim.name
    return str(dim)


def buffer_map(kernel: VTMKernel) -> dict[str, VTMBuffer]:
    """All named buffers (inputs + outputs + internal allocations)."""
    out: dict[str, VTMBuffer] = {}
    for b in kernel.inputs + kernel.outputs + kernel.buffers:
        out[b.name] = b
    return out


